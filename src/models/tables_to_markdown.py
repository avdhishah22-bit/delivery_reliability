"""Turn every CSV in reports/tables/ into markdown so the numbers can be pasted into the report.

    python -m src.utils.tables_to_markdown            # writes reports/results_tables.md
"""
from pathlib import Path

import pandas as pd


def to_md(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [f"{v:.3f}" if isinstance(v, float) else str(v) for v in r.tolist()]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def main(tables_dir: str = "reports/tables", out: str = "reports/results_tables.md"):
    parts = ["# Result tables (generated by src/utils/tables_to_markdown.py)\n"]
    for f in sorted(Path(tables_dir).glob("*.csv")):
        df = pd.read_csv(f)
        if df.columns[0].startswith("Unnamed"):
            df = df.rename(columns={df.columns[0]: ""})
        parts.append(f"\n## {f.stem}\n\n{to_md(df)}\n")
    Path(out).write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out} from {len(parts) - 1} tables")


if __name__ == "__main__":
    main()
